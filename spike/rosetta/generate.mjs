// Rosetta spike generator: derive Orca's `window.api` surface from its preload
// types and emit (a) a shim that records every call and (b) a coverage report
// against the sidebar's usage and Hydra's Tauri commands.
import ts from 'typescript'
import path from 'node:path'
import fs from 'node:fs'

const ORCA = path.resolve(process.env.HOME, 'src/orca')
const entry = path.join(ORCA, 'src/preload/api-types.ts')
const outDir = path.resolve('spike/rosetta/generated')

const program = ts.createProgram([entry], {
  strict: true,
  target: ts.ScriptTarget.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  module: ts.ModuleKind.ESNext,
  skipLibCheck: true,
  noEmit: true
})
const checker = program.getTypeChecker()
const source = program.getSourceFile(entry)
const preload = source.statements.find(
  (s) => ts.isTypeAliasDeclaration(s) && s.name.text === 'PreloadApi'
)
if (!preload) throw new Error('PreloadApi not found')

const preloadType = checker.getTypeAtLocation(preload.name)
const groups = []
for (const prop of preloadType.getProperties()) {
  const groupType = checker.getTypeOfSymbolAtLocation(prop, preload.name)
  const methods = []
  for (const member of groupType.getProperties()) {
    const memberType = checker.getTypeOfSymbolAtLocation(member, preload.name)
    const signature = memberType.getCallSignatures()[0]
    if (!signature) continue
    const decl = signature.getDeclaration()
    const text = decl ? decl.getText().replace(/\s+/g, ' ').slice(0, 300) : ''
    methods.push({ name: member.getName(), signature: text })
  }
  groups.push({ name: prop.getName(), methods })
}

const totalMethods = groups.reduce((sum, g) => sum + g.methods.length, 0)
fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(
  path.join(outDir, 'window-api.json'),
  JSON.stringify({ generatedAt: new Date().toISOString(), groups }, null, 1)
)

// Shim: one callable per method, all routed through a single recorder so the
// spike can list exactly which calls a mounted surface makes.
const lines = [
  '// GENERATED by spike/rosetta/generate.mjs — do not edit.',
  'export type RosettaCall = { path: string; args: unknown[]; at: number; bound: boolean }',
  'export type RosettaBindings = Record<string, (...args: any[]) => any>',
  'declare global { interface Window { __rosettaLog?: RosettaCall[] } }',
  'function record(path: string, args: unknown[], bound: boolean): void {',
  '  ;(window.__rosettaLog ??= []).push({ path, args, at: Date.now(), bound })',
  '}',
  'function method(path: string, bindings: RosettaBindings, fallback?: RosettaFallback) {',
  '  return (...args: unknown[]) => {',
  '    const binding = bindings[path]',
  '    record(path, args, Boolean(binding))',
  '    if (binding) return binding(...args)',
  '    if (fallback) return fallback(path, args)',
  '    // Spike: resolve undefined so module-init probes do not abort the mount;',
  '    // the ledger is what tells us a call still needs a Hydra binding.',
  '    return Promise.resolve(undefined)',
  '  }',
  '}',
  'export type RosettaFallback = (path: string, args: unknown[]) => unknown',
  'export function createRosettaApi(',
  '  bindings: RosettaBindings = {},',
  '  fallback?: RosettaFallback',
  '): Record<string, Record<string, unknown>> {',
  '  return {'
]
for (const group of groups) {
  lines.push(`    ${JSON.stringify(group.name)}: {`)
  for (const method of group.methods) {
    lines.push(`      ${JSON.stringify(method.name)}: method(${JSON.stringify(`${group.name}.${method.name}`)}, bindings, fallback),`)
  }
  lines.push('    },')
}
lines.push('  }', '}', '')
fs.writeFileSync(path.join(outDir, 'window-api.generated.ts'), lines.join('\n'))

// Coverage: what the Orca sidebar actually calls vs what Hydra exposes.
const used = new Map()
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (/\.(ts|tsx)$/.test(entry.name) && !/\.test\./.test(entry.name)) {
      const text = fs.readFileSync(full, 'utf8')
      for (const match of text.matchAll(/window\.api\.([A-Za-z0-9_]+)(?:\.([A-Za-z0-9_]+))?/g)) {
        const key = match[2] ? `${match[1]}.${match[2]}` : `${match[1]}.*`
        used.set(key, (used.get(key) ?? 0) + 1)
      }
    }
  }
}
walk(path.join(ORCA, 'src/renderer/src/components/sidebar'))

const hydraCommands = JSON.parse(
  fs.readFileSync('docs/audits/orca-sidebar-parity/index/hydra_tauri_commands.json', 'utf8')
)
const hydraNames = new Set(hydraCommands.map((c) => c.cmd))

const generated = new Map()
for (const group of groups) {
  for (const method of group.methods) generated.set(`${group.name}.${method.name}`, true)
}

const usage = [...used.entries()]
  .map(([key, hits]) => ({ key, hits, generated: generated.has(key) }))
  .sort((a, b) => b.hits - a.hits)
const usedGroups = new Map()
for (const { key } of usage) {
  const group = key.split('.')[0]
  usedGroups.set(group, (usedGroups.get(group) ?? 0) + 1)
}

const report = {
  generatedAt: new Date().toISOString(),
  orca: {
    preloadGroups: groups.length,
    preloadMethods: totalMethods,
    sidebarDistinctCalls: usage.length,
    sidebarGroups: Object.fromEntries(usedGroups)
  },
  hydra: { tauriCommands: hydraNames.size, names: [...hydraNames].sort() },
  sidebarCalls: usage
}
fs.writeFileSync(path.join(outDir, 'coverage.json'), JSON.stringify(report, null, 1))
console.log(JSON.stringify({
  preloadGroups: groups.length,
  preloadMethods: totalMethods,
  sidebarDistinctCalls: usage.length,
  sidebarGroups: Object.fromEntries(usedGroups),
  hydraCommands: hydraNames.size
}, null, 1))
